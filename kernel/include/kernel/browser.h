#ifndef ASTRA_KERNEL_BROWSER_H
#define ASTRA_KERNEL_BROWSER_H

#include <kernel/types.h>
#include <kernel/gfx.h>
#include <kernel/input.h>
#include <kernel/wm.h>
#include <kernel/css.h>

#define BROWSER_URL_MAX         256
#define BROWSER_TITLE_MAX       64
#define BROWSER_HTML_BUFFER_MAX 16384
#define BROWSER_MAX_NODES       128
#define BROWSER_MAX_BOXES       256
#define BROWSER_MAX_HISTORY     16
#define BROWSER_STATUS_MAX      128

/* Supported URL schemes */
typedef enum {
    URL_SCHEME_UNKNOWN = 0,
    URL_SCHEME_HTTP,
    URL_SCHEME_FILE,
    URL_SCHEME_HTTPS
} browser_url_scheme_t;

typedef struct {
    browser_url_scheme_t scheme;
    char host[96];
    u16 port;
    char path[160];
    char raw[BROWSER_URL_MAX];
} browser_url_t;

/* HTML Tag types recognized by parser */
typedef enum {
    HTML_TAG_NONE = 0,
    HTML_TAG_TEXT,
    HTML_TAG_TITLE,
    HTML_TAG_H1,
    HTML_TAG_H2,
    HTML_TAG_H3,
    HTML_TAG_P,
    HTML_TAG_BR,
    HTML_TAG_HR,
    HTML_TAG_B,
    HTML_TAG_I,
    HTML_TAG_A,
    HTML_TAG_UL,
    HTML_TAG_OL,
    HTML_TAG_LI,
    HTML_TAG_DIV,
    HTML_TAG_SPAN,
    HTML_TAG_STYLE
} html_tag_type_t;

typedef struct {
    html_tag_type_t tag;
    char text[128];
    char href[128];
    char class_name[CSS_MAX_CLASS_LEN];
    char id[CSS_MAX_ID_LEN];
    css_style_t inline_style;
    css_style_t computed_style;
    bool bold;
    bool italic;
    bool is_block;
} html_node_t;

/* Render Box: formatted visual element generated by layout engine */
typedef struct {
    int x;
    int y;
    int w;
    int h;
    char text[96];
    u32 color;
    u32 bg_color;
    bool has_bg_color;
    int border_w;
    u32 border_color;
    bool has_border;
    u8 font_scale;
    bool bold;
    bool italic;
    css_text_align_t text_align;
    bool is_link;
    char href[128];
    bool is_hr;
    bool is_bullet;
    bool is_block_box;
} render_box_t;

/* Navigation history entry */
typedef struct {
    char url[BROWSER_URL_MAX];
    char title[BROWSER_TITLE_MAX];
} browser_history_entry_t;

/* Browser application state */
typedef struct {
    wm_window_t *window;
    char current_url[BROWSER_URL_MAX];
    char input_url[BROWSER_URL_MAX];
    int input_cursor;
    bool input_focused;

    char page_title[BROWSER_TITLE_MAX];
    char status_msg[BROWSER_STATUS_MAX];

    /* Raw HTML buffer */
    char html_buf[BROWSER_HTML_BUFFER_MAX];
    size_t html_len;

    /* Stylesheet extracted from <style> blocks */
    css_stylesheet_t stylesheet;

    /* Parsed DOM Nodes */
    html_node_t nodes[BROWSER_MAX_NODES];
    int node_count;

    /* Layout Render Boxes */
    render_box_t boxes[BROWSER_MAX_BOXES];
    int box_count;

    /* Viewport & Scrolling */
    int scroll_y;
    int doc_height;
    int viewport_w;
    int viewport_h;
    bool scrollbar_dragging;
    int drag_start_mouse_y;
    int drag_start_scroll_y;

    /* History Stack */
    browser_history_entry_t history[BROWSER_MAX_HISTORY];
    int history_count;
    int history_index;

    bool loading;
} browser_state_t;

/* URL & Network Helpers */
bool browser_url_parse(const char *raw, browser_url_t *out);
int browser_fetch_url(const browser_url_t *url, char *out_buf, size_t max_len, int *out_status);

/* HTML Parser & Layout */
int html_parse(const char *html, size_t len, html_node_t *nodes, int max_nodes, char *out_title, size_t title_max, css_stylesheet_t *sheet);
int browser_layout(const html_node_t *nodes, int node_count, int viewport_w, render_box_t *boxes, int max_boxes, const css_stylesheet_t *sheet, int *out_doc_h);

/* Application Lifecycle */
void app_browser_init(void);
void app_browser_launch(const char *initial_url);
void app_browser_navigate(const char *url);
bool browser_self_test(void);

#endif /* ASTRA_KERNEL_BROWSER_H */
